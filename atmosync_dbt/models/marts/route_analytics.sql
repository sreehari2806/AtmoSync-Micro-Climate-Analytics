SELECT
    ROUTE_DATE,
    ORIGIN,
    DESTINATION,
    COMMODITY,
    COUNT(ROUTE_ID) AS TOTAL_JOURNEYS,
    COUNT(DISTINCT CONTAINER_ID) AS TOTAL_CONTAINERS,
    AVG(DISTANCE_KM) AS AVERAGE_DISTANCE_KM,
    AVG(ESTIMATED_TRAVEL_HOURS) AS AVERAGE_TRAVEL_HOURS
FROM {{ ref('mock_route_history') }}
GROUP BY
    ROUTE_DATE,
    ORIGIN,
    DESTINATION,
    COMMODITY